/** 判断字符串是否含中文。 */
export function hasCjk(s: string | undefined | null): boolean {
  return !!s && CJK.test(s)
}

/** 去掉末尾的括号补充说明，如「出水量(毫升)」→「出水量」。 */
function trimParen(s: string): string {
  return s.replace(/\s*[（(][^）)]*[）)]\s*$/, '').trim() || s
}

const NUM_SUFFIX = /-\d+$/

/**
 * 查字典：先精确匹配，未命中再去掉尾部数字后缀重试
 * （如 on-10 → on）。与上游 Python 版 spec_zh 的匹配策略一致。
 */
function lookup(dict: Record<string, string>, name: string): string | undefined {
  if (!name) return undefined
  const hit = dict[name]
  if (hit) return hit
  const stripped = name.replace(NUM_SUFFIX, '')
  return stripped !== name ? dict[stripped] : undefined
}

/** 属性的中文显示名。 */
export function propLabel(def: {
  base_name?: string
  name?: string
  desc_zh?: string
  desc_en?: string
  description?: string
}): string {
  // 1. 官方中文
  if (def.desc_zh && hasCjk(def.desc_zh)) return trimParen(def.desc_zh.trim())
  // 2. 兜底字典（先 base_name，再去重后的 name）
  const byBase = lookup(PROP_ZH, def.base_name || '')
  if (byBase) return byBase
  const byName = lookup(PROP_ZH, def.name || '')
  if (byName) return byName
  // 3. 英文原文
  return def.desc_en || def.description || def.name || def.base_name || ''
}

/** 动作的中文显示名。 */
export function actionLabel(act: {
  name?: string
  desc_zh?: string
  desc_en?: string
  description?: string
}): string {
  if (act.desc_zh && hasCjk(act.desc_zh)) return trimParen(act.desc_zh.trim())
  const byName = lookup(ACTION_ZH, act.name || '')
  if (byName) return byName
  return act.desc_en || act.description || act.name || ''
}

/** 枚举值的中文显示名。 */
export function valueLabel(item: {
  description?: string
  desc_zh?: string
  value?: number | string
}): string {
  // 1. 官方中文
  if (item.desc_zh && hasCjk(item.desc_zh)) return trimParen(item.desc_zh.trim())
  // 2. 兜底字典（按英文原文）
  const key = (item.description || '').trim()
  const hit = VALUE_ZH[key]
  if (hit) return hit
  // 3. 英文原文 / 原始值
  return key || String(item.value ?? '')
}

